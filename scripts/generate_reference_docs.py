"""Generate the reference pages of the documentation from the LunarOps registries.

The program reference, the model-class reference and the Python API page stubs
are derived from the declarative program specifications, the class registry and
the package layout. Run this script after changing a schema or adding a module;
``--check`` exits with status 1 when a committed page is out of date.

Usage::

    python scripts/generate_reference_docs.py          # rewrite the pages
    python scripts/generate_reference_docs.py --check  # verify they are current
"""

