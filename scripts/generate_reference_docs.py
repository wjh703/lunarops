def cell(text: object) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def yaml_inline(value: Any) -> str:
    if value is None:
        return "`null`"
    if isinstance(value, tuple):
        value = list(value)
    text = yaml.safe_dump(value, default_flow_style=True, sort_keys=False, width=10_000).strip()
    if text.endswith("..."):
        text = text[: -len("...")].strip()
    return f"`{text}`"


def type_label(field: FieldSpec) -> str:
    category = field.class_category or ""
    if field.kind == "class":
        return f"[`{category}`](classes.md#{category.lower()}) class"
    if field.kind == "class_list":
        return f"list of [`{category}`](classes.md#{category.lower()}) classes"
    if field.kind == "sequence":
        return f"list of {field.item_kind}" if field.item_kind else "list"
    return field.kind


def constraints(field: FieldSpec) -> str:
    parts = []
    if field.required:
        parts.append("required")
    if field.allow_none:
        parts.append("nullable")
    if field.choices:
        parts.append("one of " + ", ".join(f"`{choice}`" for choice in sorted(field.choices, key=str)))
    for attribute, symbol in (("gt", ">"), ("ge", "≥"), ("lt", "<"), ("le", "≤")):
        bound = getattr(field, attribute)
        if bound is not None:
            parts.append(f"{symbol} {bound:g}")
    if field.min_items is not None and field.min_items == field.max_items:
        parts.append(f"exactly {field.min_items} items")
    else:
        if field.min_items:
            parts.append(f"at least {field.min_items} items")
        if field.max_items is not None:
            parts.append(f"at most {field.max_items} items")
    if field.unique:
        parts.append("unique items")
    return "; ".join(parts)


def default_label(field: FieldSpec) -> str:
    if field.default is MISSING or field.default == {}:
        return ""
    return yaml_inline(field.default)


def field_rows(schema: ConfigSchema, prefix: str = "", skip: frozenset[str] = frozenset()) -> list[str]:
    rows = []
    for field in schema.fields:
        if field.name in skip:
            continue
        name = f"{prefix}{field.name}"
        rows.append(
            f"| `{name}` | {type_label(field)} | {default_label(field)} | {cell(constraints(field))} "
            f"| {cell(field.description)} |"
        )
        nested = field.nested if field.nested is not None else field.item_nested
        if nested is not None and not nested.variants:
            child = f"{name}[]." if field.item_nested is not None else f"{name}."
            rows.extend(field_rows(nested, child))
    return rows


FIELD_HEADER = "| Field | Type | Default | Constraints | Description |\n|---|---|---|---|---|"


def field_table(schema: ConfigSchema, skip: frozenset[str] = frozenset()) -> str:
    rows = field_rows(schema, skip=skip)
    return FIELD_HEADER + "\n" + "\n".join(rows) if rows else "This type has no options besides `type`."


def variant_sections(schema: ConfigSchema, level: str) -> list[str]:
    sections = []
    for field in schema.fields:
        nested = field.item_nested
        if nested is None or not nested.variants:
            continue
        sections.append(f"{level} `{field.name}` entries\n")
        sections.append(
            f"Each entry of `{field.name}` is a mapping with a `type` key; the remaining keys depend on the type.\n"
        )
        for variant in nested.variants:
            sections.append(f"{level}# `{variant.type_name}`\n")
            sections.append(field_table(variant) + "\n")
    return sections


def slot_table(spec: ProgramSpec) -> str:
    rows = ["| Field | Direction | Artifact type | Required | Description |", "|---|---|---|---|---|"]
    for direction, slots in (("input", spec.inputs), ("output", spec.outputs)):
        for slot in slots:
            artifact = "external file" if slot.external else f"`{slot.artifact_type}`"
            if slot.many:
                artifact = f"list of {artifact}" if slot.external else f"list of {artifact} files"
            rows.append(
                f"| `{slot.key}` | {direction} | {artifact} | {'yes' if slot.required else 'no'} "
                f"| {cell(slot.description)} |"
            )
    return "\n".join(rows)


def ordered_specs() -> list[tuple[str, list[ProgramSpec]]]:
    ensure_builtin_programs()
    by_name = {spec.name: spec for spec in program_specs()}
    groups = []
    used: set[str] = set()
    for title, names in PROGRAM_GROUPS:
        specs = [by_name[name] for name in names if name in by_name]
        used.update(spec.name for spec in specs)
        groups.append((title, specs))
    rest = sorted(name for name in by_name if name not in used)
    if rest:
        groups.append(("Other programs", [by_name[name] for name in rest]))
    return groups


def programs_page() -> str:
    out = [
        GENERATED,
        "# Program reference\n",
        (
            "Every entry of the `programs:` list of a run configuration names one of these programs in its "
            "`program` key; the other keys of the entry are the fields listed below. Paths are resolved against "
            "the working directory. `python -m lunarops describe-program <Name>` prints the same contract.\n"
        ),
        "| Program | Purpose |\n|---|---|",
    ]
    groups = ordered_specs()
    for _, specs in groups:
        for spec in specs:
            out.append(f"| [`{spec.name}`](#{spec.name.lower()}) | {cell(spec.summary)} |")
    out.append("")
    for title, specs in groups:
        out.append(f"## {title}\n")
        for spec in specs:
            out.append(f"### {spec.name}\n")
            out.append(f"{spec.summary}\n")
            if spec.slots:
                out.append("**Files**\n")
                out.append(slot_table(spec) + "\n")
            slot_keys = frozenset(slot.key for slot in spec.slots)
            rows = field_rows(spec.schema, skip=slot_keys | _variant_fields(spec.schema))
            if rows:
                out.append("**Options**\n")
                out.append(FIELD_HEADER + "\n" + "\n".join(rows) + "\n")
            out.extend(variant_sections(spec.schema, "####"))
    return "\n".join(out).rstrip() + "\n"


def _variant_fields(schema: ConfigSchema) -> frozenset[str]:
    return frozenset(
        field.name for field in schema.fields if field.item_nested is not None and field.item_nested.variants
    )


def class_summary(category: str, type_name: str) -> str:
    if type_name == "none":
        return "Disables this model."
    declaration = _declaration(category, type_name)
    if declaration.schema.description:
        return declaration.schema.description
    factory = declaration.factory
    owner = getattr(factory, "__self__", None)
    target = owner if inspect.isclass(owner) else factory
    doc = inspect.getdoc(target) or ""
    return doc.split("\n\n", 1)[0].replace("\n", " ").strip()


def classes_page() -> str:
    out = [
        GENERATED,
        "# Model class reference\n",
        (
            "Model classes are declared as mappings with an exact `type` key, for example "
            "`troposphere: {type: mendesPavlis}`. A declaration placed on a program entry overrides the one in "
            "`observationModel:`, which overrides the one in `shared:`. Every category below except "
            "`ephemerides`, `earthRotation` and `parametrization` also accepts `{type: none}`. "
            "`python -m lunarops list-classes [category]` lists the registered types.\n"
        ),
    ]
    registered = available()
    known = [name for name, _ in CATEGORIES]
    categories = list(CATEGORIES) + [(name, "") for name in sorted(registered) if name not in known]
    for category, description in categories:
        types = registered.get(category, [])
        if not types:
            continue
        out.append(f"## {category}\n")
        if description:
            out.append(f"{description}\n")
        for type_name in types:
            out.append(f"### `{category}: {type_name}` {{#{category.lower()}-{type_name.lower()}}}\n")
            summary = class_summary(category, type_name)
            if summary:
                out.append(f"{summary}\n")
            if type_name != "none":
                out.append(field_table(_declaration(category, type_name).schema) + "\n")
    return "\n".join(out).rstrip() + "\n"


def submodules(package: str) -> list[str]:
    module = importlib.import_module(package)
    if not hasattr(module, "__path__"):
        return [package]
    names = []
    for info in pkgutil.walk_packages(module.__path__, prefix=package + "."):
        leaf = info.name.rsplit(".", 1)[-1]
        if leaf.startswith("_") or info.ispkg:
            continue
        if any(
            info.name.startswith(other + ".")
            for _, _, _, roots in API_PAGES
            for other in roots
            if other != package and other.startswith(package + ".")
        ):
            continue
        names.append(info.name)
    return sorted(names)


def api_pages() -> dict[Path, str]:
    pages = {}
    index = [
        GENERATED,
        "# Python API\n",
        (
            "The API reference is built from the docstrings of the `lunarops` package. Programs and configuration "
            "files are the supported entry points; the Python API is documented for extension work and for "
            "scripts that combine LunarOps components directly.\n"
        ),
        "| Page | Contents |\n|---|---|",
    ]
    for slug, title, summary, roots in API_PAGES:
        index.append(f"| [{title}]({slug}.md) | {cell(summary)} |")
        body = [GENERATED, f"# {title}\n", f"{summary}\n"]
        for root in roots:
            for name in submodules(root):
                body.append(f"::: {name}\n")
        pages[DOCS / "reference" / "api" / f"{slug}.md"] = "\n".join(body).rstrip() + "\n"
    pages[DOCS / "reference" / "api" / "index.md"] = "\n".join(index).rstrip() + "\n"
    return pages


def all_pages() -> dict[Path, str]:
    pages = {
        DOCS / "reference" / "programs.md": programs_page(),
        DOCS / "reference" / "classes.md": classes_page(),
    }
    pages.update(api_pages())
    return pages


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n", 1)[0])
    parser.add_argument("--check", action="store_true", help="Fail if a generated page is out of date.")
    args = parser.parse_args(argv)
    stale = []
    for path, content in all_pages().items():
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current == content:
            continue
        stale.append(path.relative_to(ROOT))
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    if args.check and stale:
        print("Out-of-date generated pages (run scripts/generate_reference_docs.py):")
        for path in stale:
            print(f"  {path}")
        return 1
    for path in stale:
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
